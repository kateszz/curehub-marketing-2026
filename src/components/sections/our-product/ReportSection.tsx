/** Bulleted list of report contents, sized like emphasized body copy. */
function Bullets({ items }: { items: ReactNode[] }) {
  return (
    <ul className="flex flex-col gap-fluid-sm text-body-lg text-snow/80">
      {items.map((item, i) => (
        <li key={i} className="flex gap-fluid-sm">
          <span className="text-brand-500">&bull;</span>
          <span>{item}</span>
        </li>
      ))}
    </ul>
  );
}

/** One image + copy pair from the "What you get" report walkthrough. */
function FeatureRow({
  image,
  alt,
  reverse = false,
  delay = 0,
  children,
}: {
  image: string;
  alt: string;
  reverse?: boolean;
  delay?: number;
  children: ReactNode;
}) {
  return (
    <Reveal delay={delay}>
      <div className="grid grid-cols-1 items-start gap-fluid-2xl lg:grid-cols-2 lg:gap-fluid-4xl">
        <div className={cn("flex flex-col gap-fluid-sm", reverse && "lg:order-2")}>
          <div className="relative aspect-[2481/3508] w-full overflow-hidden rounded-md border border-snow/10 bg-snow/5">
            <Image
              src={image}
              alt={alt}
              fill
              sizes="(min-width: 1024px) 42vw, 90vw"
              className="object-cover"
            />
          </div>
          <p className="text-body-sm text-snow/40">
            Images shown are samples for illustrative purposes only. Actual
            reports may differ in content, structure, and visual design.
          </p>
        </div>
        <div className={cn("flex flex-col gap-fluid-lg", reverse && "lg:order-1")}>
          {children}
        </div>
      </div>
    </Reveal>
  );
}

